interface Entry {
	name: string;
	content: Buffer;
	key: number;
}

/** The low byte of every UTF-16 code unit is masked with the code unit count. */
function maskName(name: string): Buffer {
	const field = Buffer.from(name, "utf16le");
	const length = field.length / 2;
	for (let position = 0; position < field.length; position += 2)
		field[position] = (field[position] ?? 0) ^ (length & 0xff);
	return field;
}

/** Exclusive-ors the payload the way the reference's opener undoes it. */
function encrypt(content: Buffer, key: number): Buffer {
	const data = Buffer.from(content);
	for (let position = 0; position < data.length; position += 1)
		data[position] =
			(data[position] ?? 0) ^ (DEFAULT_KEY[key + (position & 0xff)] ?? 0);
	return data;
}

/** Builds an `ar21` archive whose index precedes the payloads. */
function buildAr2(entries: readonly Entry[]): Buffer {
	const names = entries.map((entry) => maskName(entry.name));
	const records = names.map((name) => 1 + name.length + 12);
	const indexSize = records.reduce((total, size) => total + size, 0);
	const payloadBase = 8 + indexSize;
	const stored = entries.map((entry) => encrypt(entry.content, entry.key));
	const offsets: number[] = [];
	let running = payloadBase;
	for (const payload of stored) {
		offsets.push(running);
		running += payload.length;
	}

	const archive = Buffer.alloc(running);
	archive.write("ar21", 0, "latin1");
	archive.writeInt32LE(entries.length, 4);
	let cursor = 8;
	for (const [index, name] of names.entries()) {
		archive.writeUInt8(name.length / 2, cursor);
		cursor += 1;
		name.copy(archive, cursor);
		cursor += name.length;
		archive.writeUInt32LE((offsets[index] ?? 0) - payloadBase, cursor);
		archive.writeUInt32LE(entries[index]?.content.length ?? 0, cursor + 4);
		archive.writeUInt8(entries[index]?.key ?? 0, cursor + 8);
		cursor += 12;
	}
	let payloadOffset = payloadBase;
	for (const payload of stored) {
		payload.copy(archive, payloadOffset);
		payloadOffset += payload.length;
	}
	return archive;
}

describe("Leaf AR2 resource archive", () => {
	it("lists entries and decrypts their payloads", async () => {
		const first = Buffer.from("first leaf payload");
		const second = Buffer.from("second leaf payload, longer");
		await expectArchive({
			format: leafAr2Format,
			archive: buildAr2([
				{ name: "first.bin", content: first, key: 0 },
				{ name: "second.bin", content: second, key: 5 },
			]),
			entries: [
				{ path: "first.bin", size: first.length, content: first },
				{ path: "second.bin", size: second.length, content: second },
			],
			metadata: { entryCount: 2 },
		});
	});

	it("round-trips a non-ASCII name", async () => {
		const content = Buffer.from("utf16 name payload");
		await expectArchive({
			format: leafAr2Format,
			archive: buildAr2([{ name: "スクリプト.txt", content, key: 3 }]),
			entries: [{ path: "スクリプト.txt", size: content.length, content }],
		});
	});

	it("normalizes backslash separators", async () => {
		const content = Buffer.from("nested payload");
		const archive = await leafAr2Format.open(
			new BufferByteSource(
				buildAr2([{ name: "dir\\file.bin", content, key: 0 }]),
			),
			"sample.ar2",
		);
		expect(archive.entries[0]).toMatchObject({
			path: "dir/file.bin",
			rawPath: "dir\\file.bin",
		});
		expect(
			await consumeBuffer(
				await archive.openEntry(archive.entries[0]?.id ?? ""),
			),
		).toEqual(content);
		await archive.close();
	});

	it("wraps the key table index over the payload position", async () => {
		// A payload longer than 256 bytes exercises the key table's second row.
		const content = Buffer.alloc(600, 0x5a);
		await expectArchive({
			format: leafAr2Format,
			archive: buildAr2([{ name: "long.bin", content, key: 0x10 }]),
			entries: [{ path: "long.bin", size: content.length, content }],
		});
	});

	it("rejects a foreign signature", async () => {
		const archive = buildAr2([
			{ name: "a.bin", content: Buffer.from("x"), key: 0 },
		]);
		archive.write("ar22", 0, "latin1");
		expect(
			await leafAr2Format.detect(new BufferByteSource(archive), "sample.ar2"),
		).toBe(false);
	});

	it("rejects an insane entry count", async () => {
		const archive = buildAr2([
			{ name: "a.bin", content: Buffer.from("x"), key: 0 },
		]);
		archive.writeInt32LE(0x40000, 4);
		expect(
			await leafAr2Format.detect(new BufferByteSource(archive), "sample.ar2"),
		).toBe(false);
	});

	it("rejects a record that reaches past the archive", async () => {
		const archive = buildAr2([
			{ name: "a.bin", content: Buffer.from("x"), key: 0 },
		]);
		// The name length claims more UTF-16 code units than the record holds.
		archive.writeUInt8(0x40, 8);
		expect(
			await leafAr2Format.detect(new BufferByteSource(archive), "sample.ar2"),
		).toBe(false);
	});

	it("rejects a payload outside the archive", async () => {
		const archive = buildAr2([
			{ name: "a.bin", content: Buffer.from("x"), key: 0 },
		]);
		const record = 8 + 1 + "a.bin".length * 2;
		archive.writeUInt32LE(0x1000, record);
		expect(
			await leafAr2Format.detect(new BufferByteSource(archive), "sample.ar2"),
		).toBe(false);
	});

	it("rejects a file that is too small for its header", async () => {
		expect(
			await leafAr2Format.detect(
				new BufferByteSource(Buffer.from("ar21")),
				"sample.ar2",
			),
		).toBe(false);
	});
});
