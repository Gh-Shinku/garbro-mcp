/** One file of an archive of the engine. */
export interface GigaAllEntry {
	name: string;
	type: string;
	offset: bigint;
	unpackedSize: number;
	size: number;
	packed: boolean;
}

/** `AllOpener.TryOpen`: the files of an archive of the engine, of the name of the file. */
export function gigaAllEntries(sourcePath: string): GigaAllEntry[] | undefined {
	const table = GIGA_FILE_MAP[basename(sourcePath).toUpperCase()];
	if (!table || 0 === table.length) return undefined;
	return table.map(([name, type, offset, unpackedSize, size, packed]) => ({
		name,
		type,
		offset: BigInt(offset),
		unpackedSize,
		size,
		packed,
	}));
}

/**
 * `AllOpener.LzssUnpack`: the places of a file of the engine. The head of the places stands of the count of
 * the counts of the walk of them; a count of nought stands of the places of the file as they stand, and
 * every count behind it stands of the counts of the walk of the engine, of eight of them to a place of the
 * file. A place of the file whose count stands at one stands of a place of the file itself, and every other
 * stands of the places behind it: of the counts of the places of the walk of the engine and of the counts of
 * them, of the counts of the places of the walk of the engine itself where the counts of the places of the
 * walk of the engine stand of no counts of their own.
 */
export function unpackGigaLzss(
	input: Buffer,
	outputLength: number,
): Buffer | undefined {
	if (input.length < 4 || outputLength < 0) return undefined;
	const output = Buffer.alloc(outputLength, 0x00);
	let at = 4;
	let bitcount = input.readInt32LE(0);
	if (0 === bitcount) {
		if (at + outputLength > input.length) return undefined;
		input.copy(output, 0, at, at + outputLength);
		return output;
	}
	let bytecount = bitcount >> 3;
	let bits = 8;
	let dst = 0;
	while (dst < output.length) {
		let control = 0;
		do {
			if (at >= input.length) return undefined;
			control = input[at] ?? 0;
			at += 1;
			bytecount -= 1;
			for (let bit = 0; bit < bits && dst < output.length; bit += 1) {
				if (0 !== (control & 1)) {
					if (at >= input.length) return undefined;
					output[dst] = input[at] ?? 0;
					at += 1;
					dst += 1;
				} else {
					if (at + 2 > input.length) return undefined;
					const count = input.readUInt16LE(at);
					at += 2;
					const offset = dst - (count & 0xfff) - 1;
					let length: number;
					if (0 !== (count & 0xf000)) {
						length = (count >> 12) + 2;
					} else {
						if (at >= input.length) return undefined;
						length = (input[at] ?? 0) + 0x12;
						at += 1;
					}
					if (offset < 0) return undefined;
					for (
						let place = 0;
						place < length && dst < output.length;
						place += 1
					) {
						output[dst] = output[offset + place] ?? 0;
						dst += 1;
					}
				}
				control >>= 1;
			}
		} while (bytecount > 0);
		if (bitcount <= 0) break;
		bits = bitcount & 7;
		bitcount = 0;
	}
	return output;
}

