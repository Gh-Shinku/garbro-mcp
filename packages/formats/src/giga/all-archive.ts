async function readGigaAll(
	source: ByteSource,
	sourcePath: string,
): Promise<FixedEntry[] | undefined> {
	const walked = gigaAllEntries(sourcePath);
	if (!walked) return undefined;
	const entries: FixedEntry[] = [];
	for (const [id, entry] of walked.entries()) {
		const offset = entry.offset;
		const size = BigInt(entry.size);
		if (!checkPlacement(offset, size, source.size)) return undefined;
		entries.push({
			...createFixedEntry({
				id,
				...normalizeEntryPath(entry.name),
				offset,
				size,
				compressed: entry.packed,
				metadata: {
					type: entry.type,
					unpackedSize: entry.unpackedSize,
				} as Record<string, unknown>,
			}),
			sizeKnown: true,
		});
	}
	return entries;
}

export const gigaAllEntryOpener: FixedEntryOpener = async (source, entry) => {
	const data = Buffer.from(
		await source.readAt(entry.offset, Number(entry.size)),
	);
	if (!entry.compressed) return Readable.from([data]);
	const unpackedSize = Number(entry.metadata?.unpackedSize ?? 0);
	const places = unpackGigaLzss(data, unpackedSize);
	if (!places) {
		throw new GarbroError(
			"INVALID_ARCHIVE",
			"The places of this file of the engine stand of no walk of this port",
		);
	}
	return Readable.from([places]);
};

export const gigaAllFormat: ArchiveFormat = defineFixedArchive({
	descriptor: gigaAllDescriptor,
	detection: {
		signatures: [],
		priority: -1,
		extensionFallback: true,
	},
	async detect(source: ByteSource, sourcePath: string): Promise<boolean> {
		return (await readGigaAll(source, sourcePath)) !== undefined;
	},
	async read(source: ByteSource, sourcePath: string) {
		const entries = await readGigaAll(source, sourcePath);
		if (!entries) {
			throw new GarbroError(
				"INVALID_ARCHIVE",
				"Not an archive of the engine of Giga: its name stands in no table of the reference, or its files stand outside the file",
			);
		}
		return { entries, metadata: { count: entries.length } };
	},
	openEntry: gigaAllEntryOpener,
});
