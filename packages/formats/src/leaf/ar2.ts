/** 'ar21' */
const SIGNATURE = Buffer.from("ar21", "latin1");
const COUNT_FIELD = 4;
const INDEX_START = 8;
/** A record is the offset, the size and the key byte behind its name. */
const RECORD_TAIL_SIZE = 12;
/** The low byte of every UTF-16 code unit is exclusive-ored with the name length. */
const NAME_MASK_STRIDE = 2;

interface LeafAr2Metadata extends Record<string, unknown> {
	/** The record's key byte; it selects the first key table row. */
	key: number;
}

function leafAr2Metadata(entry: FixedEntry): LeafAr2Metadata {
	const metadata = entry.metadata ?? {};
	return { key: Number(metadata.key ?? 0) };
}

/**
 * GARbro `Ar2Opener.DecryptName`. The stored name is UTF-16, but the low byte of every code unit is
 * masked with the code unit count, so the name is unmasked before it is decoded.
 */
function decryptName(field: Buffer): string {
	const data = Buffer.from(field);
	const length = data.length / NAME_MASK_STRIDE;
	for (let position = 0; position < data.length; position += NAME_MASK_STRIDE)
		data[position] = (data[position] ?? 0) ^ (length & 0xff);
	return data.toString("utf16le");
}

/**
 * GARbro `Ar2Opener.TryOpen`. Records run from 0x08 and hold a byte name length, a UTF-16 name whose
 * low bytes are masked with the name length, the stored size, an offset that is relative to the end of
 * the whole index, and a key byte. Offsets are rebased once the walk reaches the end of the index.
 */
async function readLeafAr2Index(
	source: ByteSource,
): Promise<FixedEntry[] | undefined> {
	if (source.size < BigInt(INDEX_START)) return undefined;
	const header = await source.readAt(0n, INDEX_START);
	if (!header.subarray(0, 4).equals(SIGNATURE)) return undefined;
	const count = header.readInt32LE(COUNT_FIELD);
	if (!isSaneCount(count)) return undefined;

	interface Record {
		name: string;
		offset: bigint;
		size: bigint;
		key: number;
	}
	const records: Record[] = [];
	let indexOffset = BigInt(INDEX_START);
	for (let id = 0; id < count; id += 1) {
		if (indexOffset + 1n > source.size) return undefined;
		const nameLength = (await source.readAt(indexOffset, 1))[0] ?? 0;
		indexOffset += 1n;
		const nameSize = nameLength * NAME_MASK_STRIDE;
		const recordSize = nameSize + RECORD_TAIL_SIZE;
		if (indexOffset + BigInt(recordSize) > source.size) return undefined;
		const record = await source.readAt(indexOffset, recordSize);
		const name = decryptName(record.subarray(0, nameSize));
		const tail = nameSize;
		records.push({
			name,
			offset: BigInt(record.readUInt32LE(tail)),
			size: BigInt(record.readUInt32LE(tail + 4)),
			key: record[tail + 8] ?? 0,
		});
		indexOffset += BigInt(recordSize);
	}
	const indexEnd = indexOffset;
	const entries: FixedEntry[] = [];
	for (const [id, record] of records.entries()) {
		const offset = indexEnd + record.offset;
		if (!checkPlacement(offset, record.size, source.size)) return undefined;
		entries.push(
			createFixedEntry({
				id,
				...normalizeEntryPath(record.name),
				offset,
				size: record.size,
				packedSize: record.size,
				metadata: { key: record.key } satisfies LeafAr2Metadata,
			}),
		);
	}
	return entries.length > 0 ? entries : undefined;
}

/**
 * GARbro `Ar2Opener.OpenEntry`, which exclusive-ors the whole payload with the 512-byte key table. The
 * key byte selects the starting row, and the low byte of the position selects the column, so the index
 * into the table never leaves it.
 */
const leafAr2EntryOpener: FixedEntryOpener = async (source, entry) => {
	const size = Number(entry.packedSize);
	const data = Buffer.from(await source.readAt(entry.offset, size));
	const { key } = leafAr2Metadata(entry);
	for (let position = 0; position < data.length; position += 1)
		data[position] =
			(data[position] ?? 0) ^ (DEFAULT_KEY[key + (position & 0xff)] ?? 0);
	return Readable.from([data]);
};

