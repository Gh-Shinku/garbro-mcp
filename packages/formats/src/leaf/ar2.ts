export const leafAr2Descriptor: FormatDescriptor = {
	id: "leaf-ar2",
	name: "Leaf ar21 resource archive",
	extensions: [],
	capabilities: {
		detect: true,
		list: true,
		extract: true,
		create: false,
		encryption: false,
	},
	attribution: [
		{
			project: "GARbro",
			source: "ArcFormats/Leaf/ArcAR2.cs",
			license: "MIT",
			commit: "b09ee4570ccb1daf6ac56710ee8934dc0b8baeb0",
		},
	],
};

export const leafAr2Format: ArchiveFormat = defineFixedArchive({
	descriptor: leafAr2Descriptor,
	detection: { signatures: [{ bytes: SIGNATURE }] },
	async detect(source: ByteSource): Promise<boolean> {
		return (await readLeafAr2Index(source)) !== undefined;
	},
	async read(source: ByteSource) {
		const entries = await readLeafAr2Index(source);
		if (!entries)
			throw new GarbroError("INVALID_ARCHIVE", "Invalid Leaf AR2 layout");
		return { entries, metadata: { entryCount: entries.length } };
	},
	openEntry: leafAr2EntryOpener,
});
