export function rotByteRight(value: number, count: number): number {
	const at = count & 7;
	return ((value >> at) | (value << (8 - at))) & 0xff;
}

export function rotByteLeft(value: number, count: number): number {
	const at = count & 7;
	return ((value << at) | (value >> (8 - at))) & 0xff;
}

export interface G2Scheme {
	srcOrder: readonly number[];
	dstOrder: readonly number[];
	first: Permutation;
	second: Permutation;
	firstAction: number;
	secondAction: number;
}

export function createG2Scheme(key: number): G2Scheme | undefined {
	const hash = ((Math.imul(key, 0x5f) >>> 0) >>> 13) & 0xffff;
	const at = PERMUTATION_HASHES.indexOf(hash);
	if (at < 0) return undefined;
	const src = Math.floor(at / 150);
	let dst = Math.floor(at / 30) - 5 * src;
	if (dst >= src) dst += 1;
	const secondAction = Math.floor(at / 5) % 6;
	let firstAction = at % 5;
	if (firstAction >= secondAction) firstAction += 1;
	const srcOrder = MUTATION_ORDER[src];
	const dstOrder = MUTATION_ORDER[dst];
	const first = PERMUTATIONS[firstAction];
	const second = PERMUTATIONS[secondAction];
	if (!srcOrder || !dstOrder || !first || !second) return undefined;
	return { srcOrder, dstOrder, first, second, firstAction, secondAction };
}

export function decryptG2(
	scheme: G2Scheme,
	input: Buffer,
	length: number,
): Buffer {
	const out = Buffer.alloc(length);
	const whole = length & ~3;
	for (let i = 0; i < whole; i += 1) {
		const src = (i & ~3) + (scheme.srcOrder[i & 3] ?? 0);
		const dst = (i & ~3) + (scheme.dstOrder[i & 3] ?? 0);
		out[dst] = scheme.second(i, scheme.first(i, input[src] ?? 0)) & 0xff;
	}
	for (let i = whole; i < length; i += 1)
		out[i] = scheme.second(i, scheme.first(i, input[i] ?? 0)) & 0xff;
	return out;
}
