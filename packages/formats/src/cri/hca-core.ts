/** The place of the counts of the places of a sound of the engine behind which the reference stands of 0xFF. */
const ATH_INDEX_LIMIT = 0x28e;
const ATH_TABLE_SIZE = 0x80;
/** The counts of the key of the engine as the reference stands of them (`HcaAudio.DefaultKey`). */
export const HCA_DEFAULT_KEY: readonly [number, number] = [
	0x30dbe1ab, 0xcc554639,
];

function invalidSound(message: string): GarbroError {
	return new GarbroError("INVALID_ARCHIVE", message);
}

/**
 * The table of the counts of the places of a sound of the engine (`AthTable`). The reference stands of no
 * counts at all for the kind of no count at all, and of the counts of the list for the kind of one count;
 * every other kind is refused.
 */
export function readHcaAthTable(
	type: number,
	key: number,
): Uint8Array | undefined {
	const table = new Uint8Array(ATH_TABLE_SIZE);
	if (0 === type) return table;
	if (1 !== type) throw invalidSound("Unknown HCA ath type");
	let v = 0;
	for (let index = 0; index < ATH_TABLE_SIZE; index += 1, v += key) {
		const place = v >>> 13;
		if (place >= ATH_INDEX_LIMIT) {
			// The counts of the places of a sound of the engine behind the count of them stand of the places
			// of the count of the walk of the engine itself.
			for (let at = index; at < table.length; at += 1) table[at] = 0xff;
			break;
		}
		table[index] = ATH_LIST[place] ?? 0;
		v += key;
	}
	return table;
}

/**
 * The cipher of a sound of the engine (`Cipher`): the counts of the places of a sound of the engine stand of
 * the counts of the walk of the engine of the cipher itself, and the reference stands of no counts of them
 * where the kind of the cipher stands of the kind of the cipher of the engine of the key of the game (its own
 * `Init56` stands of no counts of the walk of the engine at all).
 */
export function createHcaCipher(
	type: number,
	key1: number,
	key2: number,
): Uint8Array {
	const table = new Uint8Array(0x100);
	// The reference stands of the counts of the walk of the engine of no cipher at all where the key of the
	// engine stands of no counts of it.
	const kind = 0 === (key1 | key2) >>> 0 ? 0 : type;
	if (0 === kind) {
		for (let index = 0; index < table.length; index += 1) table[index] = index;
		return table;
	}
	if (1 === kind) {
		for (let index = 1, v = 0; index < 0xff; index += 1) {
			v = (v * 13 + 11) & 0xff;
			// The reference stands of the count of the engine of the cipher itself again where the count of
			// it stands of no count at all, or of the count of the engine of the cipher itself.
			if (0 === v || 0xff === v) v = (v * 13 + 11) & 0xff;
			table[index] = v;
		}
		table[0] = 0;
		table[0xff] = 0xff;
		return table;
	}
	if (56 === kind) {
		// The reference stands of `throw new NotImplementedException ("Encrypted HCA streams not
		// implemented")` for the cipher of the engine of the key of the game.
		throw new GarbroError(
			"UNSUPPORTED_FEATURE",
			"The cipher of a sound of the Cri engine of the key of the game stands unported",
		);
	}
	throw invalidSound("Unknown HCA cipher type");
}

/** The counts of the places of a sound of the engine of the walk of the engine of the cipher itself. */
export function decipherHcaBlock(table: Uint8Array, block: Buffer): void {
	for (let at = 0; at < block.length; at += 1)
		block[at] = table[block[at] ?? 0] ?? 0;
}
