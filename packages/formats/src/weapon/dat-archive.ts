/** The two places of the file a picture of the engine stands of for every place of the picture. */
const PLACES_PER_PIXEL = 2;

/** `DatOpener.TryOpen`: the list of the places of the pictures of an archive of that name. */
export function weaponTableOf(
	sourcePath: string,
): readonly (readonly [number, number])[] | undefined {
	const name = sourcePath.replace(/^.*[/\\]/, "").toLowerCase();
	return WEAPON_TABLES[name];
}

/** The pictures of an archive of the engine, one behind the other from the head of the file. */
export function weaponEntries(
	sourcePath: string,
	size: bigint,
):
	| { width: number; height: number; offset: bigint; size: bigint }[]
	| undefined {
	const table = weaponTableOf(sourcePath);
	if (undefined === table) return undefined;
	const entries: {
		width: number;
		height: number;
		offset: bigint;
		size: bigint;
	}[] = [];
	let offset = 0n;
	for (const [width, height] of table) {
		const count = BigInt(width * height * PLACES_PER_PIXEL);
		if (!checkPlacement(offset, count, size)) return undefined;
		entries.push({ width, height, offset, size: count });
		offset += count;
	}
	return entries;
}

/** `CgDecoder.GetImageData`: the places of the colours of a picture, of the places of the file of it. */
export function decodeWeaponPixels(data: Buffer): Buffer {
	if (0 !== data.length % PLACES_PER_PIXEL) {
		throw new GarbroError(
			"INVALID_ARCHIVE",
			"The places of a picture of the engine stand of an odd count",
		);
	}
	const places = Buffer.from(data);
	for (let at = 0; at < places.length; at += PLACES_PER_PIXEL) {
		const first = places[at] ?? 0;
		const second = places[at + 1] ?? 0;
		const high = ((first << 2) | (second & 3)) & 0xff;
		const low = ((second >> 2) | (first & ~0x1f)) & 0xff;
		places[at] = low;
		places[at + 1] = high;
	}
	return places;
}

