export const weaponDatEntryOpener: FixedEntryOpener = async (source, entry) => {
	const width = Number(entry.metadata?.width ?? 0);
	const height = Number(entry.metadata?.height ?? 0);
	const stored = Buffer.from(
		await source.readAt(entry.offset, Number(entry.size)),
	);
	const places = decodeWeaponPixels(stored);
	return Readable.from([writeBmp16(width, height, places)]);
};

export const weaponDatFormat: ArchiveFormat = defineFixedArchive({
	descriptor: weaponDatDescriptor,
	detection: {
		signatures: [],
		priority: -1,
		extensionFallback: true,
	},
	async detect(source: ByteSource, sourcePath: string): Promise<boolean> {
		return undefined !== weaponEntries(sourcePath, source.size);
	},
	async read(source: ByteSource, sourcePath: string) {
		const table = weaponEntries(sourcePath, source.size);
		if (!table) {
			throw new GarbroError(
				"INVALID_ARCHIVE",
				"Not an archive of the engine of Weapon: its name stands in no list of the places of a picture",
			);
		}
		const base = sourcePath.replace(/^.*[/\\]/, "").replace(/\.[^.]*$/, "");
		const fixed: FixedEntry[] = table.map((entry, id) => ({
			...createFixedEntry({
				id,
				path: `${base}#${String(id).padStart(4, "0")}`,
				offset: entry.offset,
				size: entry.size,
				compressed: false,
				metadata: {
					type: "image",
					image: "bmp",
					width: entry.width,
					height: entry.height,
				} as Record<string, unknown>,
			}),
			sizeKnown: true,
		}));
		return {
			entries: fixed,
			metadata: { count: fixed.length, shape: "places-of-a-picture" },
		};
	},
	openEntry: weaponDatEntryOpener,
});
