#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const inventoryPath = resolve(root, "docs/garbro-inventory.json");
const outputPath = resolve(
	root,
	"packages/formats/src/shared/resource-catalog.generated.ts",
);
const inventory = JSON.parse(await readFile(inventoryPath, "utf8"));

if (inventory.schemaVersion !== 2)
	throw new Error("GARBro inventory schemaVersion must be 2");

const resources = inventory.formats.map((format) => ({
	type: format.type,
	tag: format.tag,
	extensions: format.extensions,
	signatures: format.signatures,
}));

const generated = `// Generated by scripts/generate-resource-catalog.mjs from docs/garbro-inventory.json.\n// Do not edit this file directly.\n\nexport const garbroResourceCatalog = ${JSON.stringify(resources, null, "\t")} as const;\n`;

await writeFile(outputPath, generated);
console.log(
	`Wrote ${resources.length} GARBro resource records to ${outputPath}`,
);
