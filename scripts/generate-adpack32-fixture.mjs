import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import iconv from "iconv-lite";

const outputDirectory = resolve(import.meta.dirname, "../fixtures/adpack32");
const entries = [
	{ path: "hello.txt", content: Buffer.from("hello adpack32\n") },
	{ path: "画像.bin", content: Buffer.from([0, 1, 2, 0xfd, 0xfe, 0xff]) },
];
const headerSize = 0x10;
const recordSize = 0x20;
const dataOffset = headerSize + (entries.length + 1) * recordSize;

function record(path, offset) {
	const result = Buffer.alloc(recordSize);
	const name = iconv.encode(path, "cp932");
	if (name.length >= 0x18) throw new Error(`Fixture path is too long: ${path}`);
	name.copy(result);
	result.writeUInt32LE(offset, 0x1c);
	return result;
}

let offset = dataOffset;
const records = entries.map((entry) => {
	const result = record(entry.path, offset);
	offset += entry.content.length;
	return result;
});
records.push(record("", offset));

const header = Buffer.alloc(headerSize);
header.write("ADPACK32", 0, "ascii");
header.writeUInt32LE(entries.length + 1, 12);
const archive = Buffer.concat([
	header,
	...records,
	...entries.map((entry) => entry.content),
]);
const manifest = {
	source:
		"Deterministic synthetic fixture generated by scripts/generate-adpack32-fixture.mjs",
	archives: {
		"basic.pak": entries.map((entry, id) => ({
			id: String(id),
			path: entry.path,
			size: String(entry.content.length),
			sha256: createHash("sha256").update(entry.content).digest("hex"),
		})),
	},
};

await mkdir(outputDirectory, { recursive: true });
await writeFile(resolve(outputDirectory, "basic.pak"), archive);
await writeFile(
	resolve(outputDirectory, "manifest.json"),
	`${JSON.stringify(manifest, null, "\t")}\n`,
);
