import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validateSupportStatus } from "./validate-support-status.mjs";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(repositoryRoot, "docs/support-status.json");
const outputPath = resolve(
	repositoryRoot,
	"packages/formats/src/support.generated.ts",
);
const source = JSON.parse(await readFile(sourcePath, "utf8"));
const taxonomy = JSON.parse(
	await readFile(
		resolve(repositoryRoot, "docs/support-gap-codes.json"),
		"utf8",
	),
);
validateSupportStatus(source, taxonomy);

const generated = `// Generated by scripts/generate-format-support.mjs from docs/support-status.json.\n// Do not edit this file directly.\n\nexport const formatSupportCatalog = ${JSON.stringify(source, null, "\t")} as const;\n`;

await writeFile(outputPath, generated);
